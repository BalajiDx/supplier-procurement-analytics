"""
Clean the raw synthetic procurement data and write Clean_*.csv plus a Cleaning Log.

Run:  python clean_dataset.py   (after generate_dataset.py)
"""
import os
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
RAW, OUT = os.path.join(HERE, "Raw Dataset"), os.path.join(HERE, "Cleaned Dataset")
os.makedirs(OUT, exist_ok=True)
log = []

# ---------------------------------------------------------------- Suppliers
s = pd.read_csv(os.path.join(RAW, "Suppliers.csv"))
clean = s.SupplierName.str.strip().str.title()
fixed = s.SupplierName != clean
s["SupplierName"] = clean
log.append(("Suppliers", "Supplier names trimmed and set to title case", int(fixed.sum())))
s.to_csv(os.path.join(OUT, "Clean_Suppliers.csv"), index=False)

# ----------------------------------------------------------------- Products
p = pd.read_csv(os.path.join(RAW, "Products.csv"))
p.to_csv(os.path.join(OUT, "Clean_Products.csv"), index=False)
log.append(("Products", "No issues found", 0))

# ----------------------------------------------------------- PurchaseOrders
o = pd.read_csv(os.path.join(RAW, "PurchaseOrders.csv"), dtype={"UnitCost": str})
n0 = len(o)
o = o.drop_duplicates(subset="POID")
log.append(("PurchaseOrders", "Duplicate POID rows removed", n0 - len(o)))
txt = o.UnitCost.str.contains("₹|,", regex=True)
o["UnitCost"] = o.UnitCost.str.replace("₹", "", regex=False).str.replace(",", "", regex=False).astype(float)
log.append(("PurchaseOrders", "UnitCost stored as text ('₹1,234.00') converted to number", int(txt.sum())))
dmy = o.OrderDate.str.contains("/")
o.loc[dmy, "OrderDate"] = pd.to_datetime(o.loc[dmy, "OrderDate"], format="%d/%m/%Y").dt.strftime("%Y-%m-%d")
log.append(("PurchaseOrders", "OrderDate in dd/mm/yyyy converted to yyyy-mm-dd", int(dmy.sum())))
neg = o.QtyReceived < 0
o.loc[neg, "QtyReceived"] = o.loc[neg, "QtyReceived"].abs()
log.append(("PurchaseOrders", "Negative QtyReceived (sign error) made positive", int(neg.sum())))
o["IsOpen"] = o.ReceivedDate.isna().astype(int)
log.append(("PurchaseOrders", "POs not yet received at 31 Dec 2024 flagged IsOpen = 1", int(o.IsOpen.sum())))
o = o.sort_values("POID")
o.to_csv(os.path.join(OUT, "Clean_PurchaseOrders.csv"), index=False)

# ----------------------------------------------------------- ChangeRequests
c = pd.read_csv(os.path.join(RAW, "ChangeRequests.csv"))
n0 = len(c)
c = c.drop_duplicates(subset="RequestID")
log.append(("ChangeRequests", "Duplicate RequestID rows removed", n0 - len(c)))
low = c.ChangeType != c.ChangeType.str.title().str.replace("Per", "per")
c["ChangeType"] = c.ChangeType.str.title().str.replace("Per", "per")
log.append(("ChangeRequests", "ChangeType text standardised", int(low.sum())))
sub, dec = pd.to_datetime(c.SubmittedAt), pd.to_datetime(c.DecisionAt)
c["HoursToDecision"] = ((dec - sub).dt.total_seconds() / 3600).round(2)
c["DecidedWithin24h"] = (c.HoursToDecision <= 24).astype(int)
is_cost = c.ChangeType.isin(["Cost Change", "Equipment Price Change"])
c["ChangePct"] = None
c.loc[is_cost, "ChangePct"] = ((c.loc[is_cost, "NewValue"].astype(float) / c.loc[is_cost, "OldValue"].astype(float) - 1) * 100).round(2)
log.append(("ChangeRequests", "Added HoursToDecision, DecidedWithin24h and ChangePct (cost requests)", len(c)))
c = c.sort_values("RequestID")
c.to_csv(os.path.join(OUT, "Clean_ChangeRequests.csv"), index=False)

finals = {"Clean_Suppliers": len(s), "Clean_Products": len(p), "Clean_PurchaseOrders": len(o), "Clean_ChangeRequests": len(c)}
with open(os.path.join(HERE, "Cleaning Log.md"), "w", encoding="utf-8") as f:
    f.write("# Data Cleaning Log\n\nGenerated by `clean_dataset.py`. Counts are rows (or values) affected.\n\n")
    f.write("| Table | Issue / action | Count |\n|---|---|---:|\n")
    for t, a, n in log:
        f.write(f"| {t} | {a} | {n:,} |\n")
    f.write("\n## Final row counts\n\n| Table | Rows |\n|---|---:|\n")
    for k, v in finals.items():
        f.write(f"| {k} | {v:,} |\n")
print(pd.DataFrame(log, columns=["Table", "Action", "Count"]).to_string(index=False))
